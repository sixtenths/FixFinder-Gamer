"""Generate proportional alpha masks for the arcade LCD from Arial glyphs."""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def emit(path, fonts):
    lines = ["/* Generated by scripts/Build-ArcadeFonts.py. */"]
    for name, font_path, size in fonts:
        font = ImageFont.truetype(str(font_path), size)
        ascent, _ = font.getmetrics()
        pixels = bytearray()
        glyphs = []
        for code in range(32, 127):
            char = chr(code)
            left, top, right, bottom = font.getbbox(char, anchor="ls")
            width, height = right - left, bottom - top
            glyphs.append((len(pixels), left, top + ascent, width, height,
                           round(font.getlength(char))))
            if not width or not height:
                continue
            mask = Image.new("L", (width, height))
            ImageDraw.Draw(mask).text((-left, -top), char, font=font, fill=255,
                                      anchor="ls")
            alpha = [(v + 8) // 17 for v in mask.tobytes()]
            alpha += [0] * (len(alpha) & 1)
            pixels.extend(alpha[i] | alpha[i + 1] << 4 for i in range(0, len(alpha), 2))
        lines.append(f"static const struct ui_glyph {name}_glyphs[] = {{")
        lines.extend("    {" + ", ".join(map(str, item)) + "}," for item in glyphs)
        lines.extend(["};", f"static const uint8_t {name}_pixels[] = {{"])
        for i in range(0, len(pixels), 16):
            lines.append("    " + ", ".join(f"0x{v:02x}" for v in pixels[i:i + 16]) + ",")
        lines.extend(["};", f"static const struct ui_font {name} = "
                      f"{{{name}_glyphs, {name}_pixels}};", ""])
    path.write_text("\n".join(lines), encoding="ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("regular", type=Path)
    parser.add_argument("bold", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    emit(args.output, [("ui_small", args.regular, 14), ("ui_large", args.bold, 26)])
